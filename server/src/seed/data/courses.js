/** Courses without a hand-written curriculum still need lessons for the player. */
export function fillerSections(title) {
  return [1, 2, 3].map((n) => ({
    name: `Module ${n} — ${title} essentials`,
    order: n - 1,
    duration: '1 Week',
    difficulty: n === 1 ? 'Beginner' : n === 2 ? 'Intermediate' : 'Advanced',
    keyTopics: ['Core concepts', 'Hands-on drill', 'Common mistakes'],
    industryRelevance: ['Apply on a live account', 'Build a portfolio artifact'],
    lessons: [1, 2, 3].map((l) => ({
      name: `${title} — lesson ${n}.${l}`,
      duration: '12:00',
      order: l - 1,
      isFreePreview: n === 1 && l === 1,
    })),
  }))
}
